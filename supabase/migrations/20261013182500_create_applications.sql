create table if not exists public.applications (
  id bigint generated by default as identity primary key,
  name text not null check (char_length(name) between 1 and 60),
  contact text not null check (char_length(contact) between 3 and 120),
  message text not null check (char_length(message) between 1 and 500),
  created_at timestamptz not null default now()
);

alter table public.applications enable row level security;

revoke all on table public.applications from anon, authenticated;
grant insert (name, contact, message) on table public.applications to anon;

drop policy if exists "Public visitors can submit applications" on public.applications;
create policy "Public visitors can submit applications"
on public.applications
for insert
to anon
with check (
  char_length(name) between 1 and 60
  and char_length(contact) between 3 and 120
  and char_length(message) between 1 and 500
);

comment on table public.applications is
  'MVP early-access applications. Public visitors may insert but cannot read rows.';
